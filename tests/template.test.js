import assert from 'node:assert/strict';
import { readdir, readFile, stat } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { test } from 'node:test';

import { TEMPLATES, planScaffold, renderScaffold } from '../src/scaffold.js';

const TEMPLATE_DIR = fileURLToPath(new URL('../templates/host-tool', import.meta.url));

/** Ids used to produce the checked-in reference copy (see its README). */
const REFERENCE_OPTIONS = {
  template: 'host-tool',
  pluginId: 'sample-plugin',
  packageName: 'sample-plugin',
  toolName: 'sample_hello',
};

async function listFiles(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) files.push(...(await listFiles(join(directory, entry.name), relative)));
    else files.push(relative);
  }
  return files.sort();
}

test('the checked-in template reference matches the renderer byte for byte', async () => {
  const planned = planScaffold({ target: '/nonexistent/host-tool-sample', ...REFERENCE_OPTIONS });
  assert.equal(planned.ok, true, JSON.stringify(planned.issues));
  const rendered = renderScaffold(planned.plan);

  // `README.md` here is the directory's own explanation; the rendering's
  // README lives at `templates/host-tool/generated-readme.md` instead.
  const onDisk = (await listFiles(TEMPLATE_DIR)).filter((path) => path !== 'README.md' && path !== 'generated-readme.md');
  assert.deepEqual(onDisk, [...rendered.keys()].filter((path) => path !== 'README.md').sort(), 'template directory and rendered file set differ');

  for (const [path, expected] of rendered) {
    if (path === 'README.md') {
      assert.equal(await readFile(join(TEMPLATE_DIR, 'generated-readme.md'), 'utf8'), expected, 'generated-readme.md differs from the rendering');
      continue;
    }
    const actual = await readFile(join(TEMPLATE_DIR, path), 'utf8');
    assert.equal(actual, expected, `${path} differs from its rendering; regenerate the reference copy or fix the renderer`);
  }
});

test('the template directory README explains that it is a generated review copy', async () => {
  const readme = await readFile(join(TEMPLATE_DIR, 'README.md'), 'utf8');
  assert.match(readme, /review copy/i);
  assert.match(readme, /byte for byte/);
  // The generated project README is kept separately so the directory README
  // can describe the copy without being compared to a rendering.
  assert.match(readme, /package\.json` \(`name`\) and `README\.md`/);
});

test('no generated file starts a process, reads the environment or registers anything globally', async () => {
  const planned = planScaffold({ target: '/nonexistent/acme', pluginId: 'acme', packageName: 'acme', toolName: 'acme_hello' });
  const banned = [/child_process/, /node:http/, /globalThis\./, /process\.env/, /setInterval|setTimeout/, /require\(/];
  for (const [path, content] of renderScaffold(planned.plan)) {
    for (const pattern of banned) {
      assert.doesNotMatch(content, pattern, `${path} matches ${pattern}`);
    }
  }
});

test('generated index.js only uses the reviewed host API surface', async () => {
  const planned = planScaffold({ target: '/nonexistent/acme', pluginId: 'acme', packageName: 'acme', toolName: 'acme_hello' });
  const index = renderScaffold(planned.plan).get('index.js');
  // Exact imports the reviewed 0.2.2-alpha.2 sources expose.
  assert.match(index, /^import Schema from '@deepseek-ai\/schemastery';$/m);
  assert.match(index, /^import \{ defineTool \} from '@deepseek-ai\/dsh-tools';$/m);
  // The registration is effect-owned: no manual tracking, no disposer caching.
  // Code (not prose) is what matters, so comments are stripped first.
  const code = index
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .split('\n')
    .filter((line) => !line.trim().startsWith('*') && !line.trim().startsWith('//'))
    .join('\n');
  assert.doesNotMatch(code, /dispose|disposer|unregister|registry/);
  assert.match(index, /ctx\.tools\.register\(\s*\n\s*defineTool\(\{/);
  // Only fields the reviewed ToolDefinition/JSON-Schema subset allows.
  assert.doesNotMatch(index, /minLength|pattern|timeoutMs|restrict\(|guard\(/);
});

test('the default template stays kit-free while two variants depend on the kit', () => {
  // The catalog now lists two templates that record `dependencies['dsh-plugin-kit']`
  // and mount through an external service. The default one must not have grown
  // either: it is the only template that works with no operator setup at all.
  // Naming the kit as provenance ("generated by dsh-plugin-kit") is allowed and
  // does not count — an import or a dependency does.
  assert.deepEqual(Object.keys(TEMPLATES), ['host-tool', 'host-tool-managed', 'host-tool-admitted']);
  const hosts = new Set(Object.values(TEMPLATES).map((template) => template.referenceHost));
  assert.equal(hosts.size, 1, 'all three templates target the same reference host');

  const planned = planScaffold({ target: '/nonexistent/host-tool-sample', ...REFERENCE_OPTIONS });
  assert.equal(planned.ok, true, JSON.stringify(planned.issues));
  const files = renderScaffold(planned.plan);

  // No kit specifier was needed, and none was recorded.
  assert.equal('kitSpecifier' in planned.plan, false);
  for (const [path, content] of files) {
    assert.doesNotMatch(content, /from 'dsh-plugin-kit/, `${path} imports the kit, which the default template must not`);
    assert.doesNotMatch(content, /pluginAdmission|ADMISSION_SERVICE|admission-provider/, `${path} carries admission wiring`);
  }

  const pkg = JSON.parse(files.get('package.json'));
  assert.equal(pkg.dependencies, undefined, 'the default template records no runtime dependency at all');

  // The default resource scope is still the static `plugin` label: the admitted
  // template's `global` claim is a separate constant, not a change to this one.
  const declaration = JSON.parse(files.get('declaration.json'));
  assert.deepEqual(declaration.resources, [{ kind: 'tool', name: REFERENCE_OPTIONS.toolName, scope: 'plugin' }]);
});

test('the template reference is not a runnable package root', async () => {
  // It is deliberately not installed or booted by this repository's tests: the
  // shared host packages are absent here, so the emitted import would fail.
  const info = await stat(join(TEMPLATE_DIR, 'index.js'));
  assert.equal(info.isFile(), true);
});
